CREATE TABLE underlying_assets(
    symbol VARCHAR PRIMARY KEY,
    last_price DECIMAL,
    updated_at TIMESTAMP
);

   
CREATE TABLE options_contracts(
    contract_id VARCHAR PRIMARY KEY,
    symbol VARCHAR,
    open_date DATE,
    expiration_date DATE,
    dte INTEGER,
    strike_price DECIMAL,
    option_type VARCHAR CHECK (option_type IN ('call', 'put')),
    multiplier INTEGER,
    CONSTRAINT FK_underlying
    FOREIGN KEY(symbol) REFERENCES underlying_assets(symbol)
);

CREATE TABLE options_quote_history(
    quote_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id VARCHAR,
    timestamp TIMESTAMPTZ,
    bid DECIMAL,
    ask DECIMAL,
    last_price DECIMAL,
    volume INTEGER,
    open_interest INTEGER,
    implied_volatility INTEGER,
    delta DECIMAL,
    gamma DECIMAL,
    theta DECIMAL,
    vega DECIMAL,
    CONSTRAINT FK_contracts
    FOREIGN KEY(contract_id) REFERENCES options_contracts(contract_id)
);


